"""Launch AMCL then Nav2, staging map files under ASCII paths for map_server."""
import os
import shutil
import tempfile

import yaml

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription, OpaqueFunction, TimerAction
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration, PathJoinSubstitution
from launch_ros.substitutions import FindPackageShare


def _stage_map_ascii(source_yaml):
    """Copy YAML and raster to an ASCII-only temp path for ROS map_server."""
    source_yaml = os.path.abspath(source_yaml)
    with open(source_yaml, encoding='utf-8') as stream:
        map_config = yaml.safe_load(stream)
    image_name = map_config['image']
    source_image = image_name if os.path.isabs(image_name) else os.path.join(
        os.path.dirname(source_yaml), image_name)
    stage_dir = tempfile.mkdtemp(prefix='tb4w5_map_')
    staged_image = os.path.join(stage_dir, os.path.basename(image_name))
    shutil.copy2(source_image, staged_image)
    map_config['image'] = staged_image
    staged_yaml = os.path.join(stage_dir, 'map.yaml')
    with open(staged_yaml, 'w', encoding='utf-8') as stream:
        yaml.safe_dump(map_config, stream, sort_keys=False)
    return staged_yaml


def _launch_navigation(context, *args, **kwargs):
    nav_share = FindPackageShare('turtlebot4_navigation')
    map_file = _stage_map_ascii(LaunchConfiguration('map').perform(context))
    use_sim_time = LaunchConfiguration('use_sim_time')
    nav_params = LaunchConfiguration('params_file')

    localization = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(PathJoinSubstitution([nav_share, 'launch', 'localization.launch.py'])),
        launch_arguments={'map': map_file, 'use_sim_time': use_sim_time}.items(),
    )
    navigation = IncludeLaunchDescription(
        PythonLaunchDescriptionSource(PathJoinSubstitution([nav_share, 'launch', 'nav2.launch.py'])),
        launch_arguments={'params_file': nav_params, 'use_sim_time': use_sim_time}.items(),
    )
    return [localization, TimerAction(period=4.0, actions=[navigation])]


def generate_launch_description():
    nav_share = FindPackageShare('turtlebot4_navigation')
    week5_share = FindPackageShare('turtlebot4_week5')
    return LaunchDescription([
        DeclareLaunchArgument(
            'map',
            default_value=PathJoinSubstitution([week5_share, 'maps', 'warehouse_slam.yaml']),
            description='Map YAML generated by the week 4 SLAM survey; replace with another compatible map if needed.'),
        DeclareLaunchArgument('use_sim_time', default_value='true'),
        DeclareLaunchArgument('params_file', default_value=PathJoinSubstitution([nav_share, 'config', 'nav2.yaml'])),
        OpaqueFunction(function=_launch_navigation),
    ])
